/// Draws one of [AppIcons]. Colour defaults to the ambient icon colour passed
/// by the caller; set [filled] for solid shapes such as the play triangle.
class AppIcon extends StatelessWidget {
  const AppIcon(
    this.paths, {
    super.key,
    required this.color,
    this.size = 20,
    this.strokeWidth = 2.25,
    this.filled = false,
  });

  final String paths;
  final Color color;
  final double size;
  final double strokeWidth;
  final bool filled;

  String get _hex {
    final rgb = color.toARGB32() & 0xFFFFFF;
    return '#${rgb.toRadixString(16).padLeft(6, '0')}';
  }

  @override
  Widget build(BuildContext context) {
    final paint = filled
        ? 'fill="$_hex" stroke="none"'
        : 'fill="none" stroke="$_hex" stroke-width="$strokeWidth" '
              'stroke-linecap="round" stroke-linejoin="round"';
    return SvgPicture.string(
      '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" $paint>$paths</svg>',
      width: size,
      height: size,
    );
  }
}
